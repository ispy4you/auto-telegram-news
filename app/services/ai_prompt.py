"""Промпт генерации: правила от пользователя + данные новости + формат ответа.

Раньше настройки предлагали править два поля — «системный промпт» и «шаблон
пользовательского промпта». Названия пришли из API модели, а не из задачи
пользователя, правила стиля дублировались в обоих полях и расходились после
первой же правки, а в редактируемом шаблоне лежал JSON-контракт: стоило его
случайно стереть, и разобрать ответ становилось нечем.

Поэтому правит пользователь один текст, данные новости приклеиваются сами, а
формат ответа живёт здесь и в форму не попадает.
"""

from app.services import prompt_template

#: Правила, которые пользователь видит и правит в настройках.
DEFAULT_AI_PROMPT = """Ты редактор новостного Telegram-канала. Перепиши исходную новость в короткий, ясный и нейтральный пост на русском языке.

Стиль: информационный, без воды, без эмодзи, без хештегов, без кликбейта.
Отдельный заголовок первой строкой не нужен, если он выглядит искусственно.
Длина: столько, сколько нужно, чтобы изложить факты из исходника.

Используй только факты из исходного текста. Не выдумывай факты, цифры, имена, причины и последствия.
Не добавляй ссылку на источник, если она не нужна по смыслу.

Если фактов не хватает на самостоятельный пост или исходник рекламный — откажись от новости и коротко объясни почему."""

#: Формат ответа. Имена полей — договор с кодом, а не настройка стиля,
#: поэтому они не редактируются и уходят отдельным системным сообщением.
RESPONSE_CONTRACT = """Отвечай строго одним JSON-объектом, без markdown-обёртки и без пояснений вокруг:
{"suitable": true, "text": "готовый текст поста", "reason": ""}

Если поста не получается — реклама, мусор, слишком мало фактов:
{"suitable": false, "text": "", "reason": "почему не подходит"}"""

#: Подписи к данным новости, когда пользователь не расставил плейсхолдеры сам.
FIELD_LABELS = (
    ("source_title", "Источник"),
    ("published_at_source", "Дата исходной публикации"),
    ("has_media", "Есть медиа"),
)


def build_user_message(rules: str, values: dict[str, str]) -> str:
    """Правила пользователя плюс те данные новости, которые он не расставил сам.

    Плейсхолдеры остались для тех, кому важно место: написал `{original_text}`
    в середине — текст встанет туда и второй раз не приедет.
    """
    used = prompt_template.used(rules)
    parts = [prompt_template.render(rules, values).rstrip()]

    fields = [f"{label}: {values.get(key, '')}" for key, label in FIELD_LABELS if key not in used]
    if fields:
        parts.append("\n".join(fields))
    if "original_text" not in used:
        parts.append('Исходный текст:\n"""\n' + (values.get("original_text") or "") + '\n"""')

    return "\n\n".join(part for part in parts if part)


#: Пример для справки в настройках: показать, что именно приклеивается
#: к правилам. Значения выдуманные, структура — ровно та, что уйдёт в модель.
SAMPLE_VALUES = {
    "source_title": "РИА Новости",
    "published_at_source": "2026-08-30 09:15",
    "original_text": "…полный текст исходной новости…",
    "has_media": "да",
}


def appendix_example() -> str:
    """Что уходит в модель помимо правил, когда плейсхолдеры не расставлены."""
    return build_user_message("", SAMPLE_VALUES)
